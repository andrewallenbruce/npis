test_that("arithmetic works on npi-npi", {
  x <- generate(n = 100, valid = TRUE)
  y <- npi(x)
  expect_equal(max(y) - min(y) + min(y), max(x) - min(x) + min(y))
  expect_equal(max(y) / min(y), max(x) / min(x))
  expect_equal(max(y) %/% min(y), max(x) %/% min(x))
  expect_equal(max(y) %% min(y), max(x) %% min(x))
  expect_equal(range(y), c(min(y), max(y)))
  expect_equal(sum(y), sum(x))
  expect_equal(mean(y), mean(x))
  expect_equal(median(y), median(x))
  expect_equal(quantile(y), quantile(x))
})
