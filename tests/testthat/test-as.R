test_that("`as_npi()` works", {
  expect_equal(
    as_npi(c(
      "1234567893",
      "1234567893L",
      1234567893.00,
      1234567893,
      1234567893L,
      NA
    )),
    as_npi(c(
      "1234567893",
      NA,
      1234567893.00,
      1234567893,
      1234567893L,
      NA
    ))
  )
})
